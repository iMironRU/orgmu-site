// Формат файла рейтинговых списков — то, что в бою отдаёт 1С напрямую (кладёт
// на сервер отдельным файлом, страница грузит его fetch-ем). Здесь тип и
// описание полей одновременно служат спецификацией для 1С-выгрузки.
//
// Данные ОБЕЗЛИЧЕНЫ: человека представляет только уникальный код (не ФИО, не
// СНИЛС в открытую). Обезличивание — на стороне 1С, в запросе.

export type SpisokRow = {
  /** Уникальный код абитуриента из личного кабинета. Публичный идентификатор. */
  code: string;
  /** Позиция в конкурсе (ранг). */
  n: number;
  /** Сумма конкурсных баллов. */
  sum: number;
  /** Баллы за вступительные испытания (без ИД). */
  vi: number;
  /** Баллы за индивидуальные достижения. */
  id: number;
  /** Баллы по каждому предмету ВИ, в порядке испытаний. */
  subj: number[];
  /** Приоритет этого заявления у абитуриента. */
  pr: number;
  /** Это высший приоритет абитуриента (куда он реально зачисляется при проходе). */
  hp: boolean;
  /** Подано согласие на зачисление. */
  cons: boolean;
  /** Принёс оригинал документа. */
  orig: boolean;
  /** Есть преимущественное право. */
  pref: boolean;
  /** Поступает без вступительных испытаний. */
  bvi: boolean;
};

export type Competition = {
  /** Идентификатор конкурса (КодКонкурса). */
  id: number;
  /** Специальность: «Лечебное дело». Для группировки во вкладки. */
  program: string;
  /** Полное название конкурса: «Лечебное дело. Основные места». */
  title: string;
  /** Квота внутри программы: «Основные места», «Отдельная квота», «Особая квота». */
  quota: string;
  form: string;
  basis: string;
  category: string;
  /** Число мест по плану набора. 0 — на дату среза места не заданы. */
  seats: number;
  /** Подано заявлений в конкурс. */
  applied: number;
  /** Подано согласий в конкурс. */
  consents: number;
  rows: SpisokRow[];
};

export type Spiski = {
  /** Момент формирования выгрузки (ISO). В бою проставляет 1С. */
  updated: string;
  competitions: Competition[];
};

// Одно заявление абитуриента для режима «найти себя»: строка + к какому
// конкурсу относится. Собирается на клиенте по коду из всех конкурсов.
export type Application = SpisokRow & { comp: Competition };
